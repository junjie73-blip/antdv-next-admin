/**
 * 确定性序列 —— 替代演示组件里遗留的运行时随机数调用。
 *
 * 图表/数字动画仍需要一组会变化的数值，但不允许是运行时随机生成：
 * 这里用一份手写常量表循环取值，每次页面装载从表头开始，刷新结果一致、可断言。
 */

const FRACTIONS = [
  0.12, 0.37, 0.58, 0.73, 0.91, 0.05, 0.44, 0.66, 0.82, 0.29, 0.51, 0.18, 0.94,
  0.63, 0.07, 0.4, 0.86, 0.25, 0.7, 0.33, 0.15, 0.48, 0.77, 0.21, 0.6, 0.34,
  0.89, 0.09, 0.55, 0.98,
] as const;

let cursor = 0;

/** 返回 [0, 1) 区间的确定性数值，调用形态与运行时随机数一致 */
export function deterministicRatio(): number {
  return FRACTIONS[cursor++ % FRACTIONS.length]!;
}
